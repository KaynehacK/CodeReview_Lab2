/*
 * Дан циклический двусвязный линейный список и указатель первый элемент этого
 * списка. Необходимо удалить в списке все элементы, у которых правый и левый
 * сосед совпадают. Если таких элементов нет, то оставить список без
 * изменений. Первый и последний элементы считать соседями. В результате
 * вернуть ссылку на последний элемент полученного списка. Все динамические
 * структуры данных реализовывать через классы. Не использовать STL. Для
 * каждой динамической структуры должен быть предусмотрен стандартный набор
 * методов - добавления/удаления/вывода элементов. Во всех задачах обязательно
 * наличие дружественного интерфейса. Ввод данных с клавиатуры.
 */

#include "Task04DoubleLinkedList.h"
#include <iostream>

using namespace std;

int main() {
    DoubleLinkedList list;
    int num_elements = 0;
    int element_value = 0;

    cout << "Введите количество элементов: ";
    cin >> num_elements;

    cout << "Введите элементы:" << endl;
    for (int i = 0; i < num_elements; i++) {
        cin >> element_value;
        list.PushBack(element_value);
    }

    cout << "Исходный список: ";
    list.PrintList();

    DoubleLinkedList::Node* tail = list.RemoveNodesWithEqualNeighbors();

    cout << "Результирующий список: ";
    list.PrintList();

    if (tail) {
        cout << "Значение хвоста: " << tail->data << endl;
    } else {
        cout << "Список пуст" << endl;
    }

    return 0;
}