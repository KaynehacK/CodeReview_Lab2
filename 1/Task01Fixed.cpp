/*
 * Дано число D и указатель P1 на вершину непустого стека.
 * Добавить элемент со значением D в стек и вывести адрес P2 новой вершины
 * стека.
 *
 * Для каждой динамической структуры должен быть предусмотрен стандартный набор
 * методов - добавления/удаления/вывода элементов. Во всех задачах обязательно
 * наличие дружественного интерфейса. Ввод данных с клавиатуры.
 *
 * В заданиях подгруппы структура «стек» (stack) моделируется цепочкой связанных
 * узлов-записей типа TNode. Поле Next последнего элемента цепочки равно
 * nullptr. Вершиной стека (top) считается первый элемент цепочки. Для доступа к
 * стеку используется указатель на его вершину (для пустого стека данный
 * указатель полагается равным nullptr). Значением элемента стека считается
 * значение его поля Data
 */

#include "Task01Stack.h"
using namespace std;


int main() {
    Stack stack;
    int n = 0;
    int value = 0;

    cout << "Сколько чисел вы хотите добавить в стек? ";
    if (!(cin >> n) || n <= 0) {
        cerr << "Некорректный ввод количества элементов" << endl;
        return 1;
    }

    for (int i = 0; i < n; i++) {
        cout << "Введите число " << i + 1 << ": ";
        if (!(cin >> value)) {
            cerr << "Некорректный ввод числа" << endl;
            return 1;
        }
        stack.push(value);
    }

    stack.ShowAddress();
    cout << "Элементы в стеке: ";
    stack.Show();

    int d;
    cout << "Введите значение D для добавления в стек: ";
    if (!(cin >> d)) {
        cerr << "Некорректный ввод числа D" << endl;
        return 1;
    }

    stack.push(d);
    cout << "Элементы в новом стеке: ";
    stack.Show();
    stack.ShowAddress();

    if (!stack.IsEmpty()) {
        cout << "Значение новой вершины: " << stack.get() << endl;
    } else {
        cerr << "Стек пуст!" << endl;
    }

    return 0;
}